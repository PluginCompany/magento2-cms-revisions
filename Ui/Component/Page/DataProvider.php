namespace PluginCompany\CmsRevisions\Ui\Component\Page;

use Magento\Framework\Api\FilterBuilder;
use Magento\Framework\Api\Search\SearchCriteriaBuilder;
use Magento\Framework\App\RequestInterface;
use Magento\Framework\View\Element\UiComponent\DataProvider\Reporting;

class DataProvider extends \Magento\Framework\View\Element\UiComponent\DataProvider\DataProvider
{
    /**
     * @param string $name
     * @param string $primaryFieldName
     * @param string $requestFieldName
     * @param Reporting $reporting
     * @param SearchCriteriaBuilder $searchCriteriaBuilder
     * @param RequestInterface $request
     * @param FilterBuilder $filterBuilder
     * @param array $meta
     * @param array $data
     */
    public function __construct(
        $name,
        $primaryFieldName,
        $requestFieldName,
        Reporting $reporting,
        SearchCriteriaBuilder $searchCriteriaBuilder,
        RequestInterface $request,
        FilterBuilder $filterBuilder,
        array $meta = [],
        array $data = []
    ) {
        
        parent::__construct(
            $name,
            $primaryFieldName,
            $requestFieldName,
            $reporting,
            $searchCriteriaBuilder,
            $request,
            $filterBuilder,
            $meta,
            $data
        );
        
        $this->addPageIdFilter();
    }
    
    public function addPageIdFilter()
    {
        $this->searchCriteriaBuilder
            ->addFilter($this->generatePageIdFilterObject());
        return $this;
    }
    
    public function getCurrentPageId()
    {
        return $this->request->getParam('page_id', 10000000);
    }
    
    private function generatePageIdFilterObject()
    {
        return $this->filterBuilder
            ->create()
            ->setField('page_id')
            ->setValue($this->getCurrentPageId());
    }
}
